from enum import Enum


class FailureCategory(str, Enum):
    LOGIC_ERROR = "LOGIC_ERROR"
    EDGE_CASE = "EDGE_CASE"
    INPUT_PARSING = "INPUT_PARSING"
    OUTPUT_FORMAT = "OUTPUT_FORMAT"
    COMPLEXITY = "COMPLEXITY"
    TIMEOUT = "TIMEOUT"
    RUNTIME_EXCEPTION = "RUNTIME_EXCEPTION"
    CONSTRAINT_VIOLATION = "CONSTRAINT_VIOLATION"
    MISUNDERSTOOD_PROBLEM = "MISUNDERSTOOD_PROBLEM"
    BAD_TEST_ORACLE = "BAD_TEST_ORACLE"
    REPEATED_SOLUTION = "REPEATED_SOLUTION"
    UNKNOWN = "UNKNOWN"


JUDGE_FAILURE_CATEGORIES = frozenset(
    {"NONE", *(category.value for category in FailureCategory)}
)
